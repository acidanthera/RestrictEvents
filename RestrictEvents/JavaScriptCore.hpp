// JavaScriptCore.framework
// JavaScriptCore hardcodes AVX support starting from macOS 15.2/Safari 18.2
// (https://github.com/WebKit/WebKit/commit/c15e741266db8ff9df309ce9971eda1cfd9021cc).
// As we can run on Macs/hacks without AVX support, we need to patch this back.
// This patch is split across the dyld cache (for macOS 15.2+) and the Safari cryptex (for Safari 18.2+, which supports Ventura+).

